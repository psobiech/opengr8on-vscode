/**
 * LuaLS definition file for a project: one class per interface object type with typed get / set /
 * execute overloads per index, and one global per object on each CLU (IO ids, the CLU, remote CLU
 * proxies). Written to .opengr8on/luals/ and added to Lua.workspace.library. Pure.
 */
import type { InterfaceRegistry, ParsedFeature, ParsedInterface, ParsedMethod } from "opengr8on-node/client";
import type { Clu } from "../project/model";
import { cluInterface, ioObject, objectInterface } from "../project/interfaces";

const luaType = (t: string | undefined) => (t === "str" ? "string" : t === "bool" ? "boolean" : t === "void" || !t ? "nil" : "number");
const ident = (s: string) => s.replace(/[^A-Za-z0-9_]/g, "_").replace(/^(\d)/, "_$1");
const oneLine = (s: string) => s.replace(/\s+/g, " ").trim();

function featureDoc(f: ParsedFeature): string {
  const bits = [f.type, f.range ? `range ${f.range}` : "", f.unit && f.unit !== "-" ? f.unit : "", f.set ? "" : "read-only"].filter(Boolean);
  const enums = f.enums.length ? ` (${f.enums.map((e) => `${e.value}=${e.name}`).join(", ")})` : "";
  return oneLine(`${f.name} [${f.index}]: ${bits.join(", ")}${enums}`);
}

function methodSig(m: ParsedMethod): string {
  return m.params.map((p) => `${ident(p.name)}: ${luaType(p.type)}`).join(", ");
}

/** `---@class` block for one interface. */
function classBlock(name: string, iface: ParsedInterface, doc: string): string[] {
  const out = [`---${oneLine(doc)}`, `---@class ${name} : GrentonObject`, `local ${name} = {}`, ""];
  const gets = iface.features.filter((f) => f.get);
  const sets = iface.features.filter((f) => f.set);
  if (gets.length) {
    out.push("---Reads a feature.");
    for (const f of gets) out.push(`---@overload fun(self: ${name}, index: ${f.index}): ${luaType(f.type)} # ${featureDoc(f)}`);
    out.push(`---@param index integer`, `---@return any`, `function ${name}:get(index) end`, "");
  }
  if (sets.length) {
    out.push("---Writes a feature.");
    for (const f of sets) out.push(`---@overload fun(self: ${name}, index: ${f.index}, value: ${luaType(f.type)}) # ${featureDoc(f)}`);
    out.push(`---@param index integer`, `---@param value any`, `function ${name}:set(index, value) end`, "");
  }
  const execs = iface.methods.filter((m) => m.call === "execute");
  if (execs.length) {
    out.push("---Calls a method.");
    for (const m of execs) {
      const params = methodSig(m);
      out.push(`---@overload fun(self: ${name}, index: ${m.index}${params ? `, ${params}` : ""}): ${luaType(m.return)} # ${m.name}`);
    }
    out.push(`---@param index integer`, `---@param ... any`, `---@return any`, `function ${name}:execute(index, ...) end`, "");
  }
  if (iface.events.length) {
    out.push(`---Binds a handler to an event: ${iface.events.map((e) => `${e.address}=${e.name}`).join(", ")}`);
    out.push(`---@param index integer`, `---@param handler fun()`, `function ${name}:add_event(index, handler) end`, "");
  }
  return out;
}

const PRELUDE = `---@meta opengr8on
-- Generated by OpenGr8on from the project and the device interface XMLs. Do not edit.

---@class GrentonObject
local GrentonObject = {}
---@param index integer
---@return any
function GrentonObject:get(index) end
---@param index integer
---@param value any
function GrentonObject:set(index, value) end
---@param index integer
---@param ... any
---@return any
function GrentonObject:execute(index, ...) end
---@param index integer
---@param handler fun()
function GrentonObject:add_event(index, handler) end

---Remote CLU proxy: execute(0, "<lua>") runs Lua on that CLU.
---@class RemoteCLU : GrentonObject
local RemoteCLU = {}

---@param name string
---@param value any
function setVar(name, value) end
---@param name string
---@return any
function getVar(name) end
---@param value any
---@return boolean
function toboolean(value) end
`;

/** LuaLS plugin: OM script notation `A->B->C` is parsed as `A.B.C` (diagnostics + completion). */
export const PLUGIN = `-- Generated by OpenGr8on: lets LuaLS read OM script notation CLU->OBJECT->Member as CLU.OBJECT.Member.
function OnSetText(uri, text)
  if not uri:find("/scripts/", 1, true) then return nil end
  local diffs = {}
  -- every "->" between a name character and a name start; nothing is consumed around it, so
  -- one-letter names (CLU->t->Start()) are handled too
  local init = 1
  while true do
    local s, e = text:find("->", init, true)
    if not s then break end
    if s > 1 and text:sub(s - 1, s - 1):match("[%w_]") and text:sub(e + 1, e + 1):match("[%a_]") then
      diffs[#diffs + 1] = { start = s, finish = e, text = "." }
    end
    init = e + 1
  end
  return diffs
end
`;

/** Field-style view of an interface for OM notation: features as fields, execute / set methods as functions. */
function arrowClass(name: string, base: string | undefined, iface: ParsedInterface | undefined, doc: string): string[] {
  const out = [`---${oneLine(doc)} (OM notation CLU->OBJECT->Member)`, `---@class ${name}${base ? ` : ${base}` : ""}`];
  const isId = (n: string) => /^[A-Za-z_]\w*$/.test(n); // e.g. "Value%" cannot be written in OM notation
  // features without get (HttpListener ResponseBody, ...) hold tables, readable on their own CLU
  for (const f of iface?.features.filter((x) => (x.get || x.set) && isId(x.name)) ?? []) {
    out.push(`---@field ${f.name} ${f.get ? luaType(f.type) : "table|string"} # ${featureDoc(f)}${f.get ? "" : " (table; read on its own CLU only)"}`);
  }
  // execute methods and set-type methods (SetMode(0) → ID:set(i, 0)); both are callable in OM notation
  for (const m of iface?.methods.filter((x) => (x.call === "execute" || x.call === "set") && isId(x.name)) ?? []) {
    out.push(`---@field ${m.name} fun(${methodSig(m)}): ${luaType(m.return)} # ${m.name} [${m.index}]`);
  }
  out.push(`local ${name} = {}`, "");
  return out;
}

export interface StubResult {
  text: string;
  /** object ids declared on more than one CLU with different classes (last one wins in LuaLS) */
  conflicts: string[];
}

export function luaStubs(clus: Clu[], registry: InterfaceRegistry): StubResult {
  const classes = new Map<string, string[]>();
  const globals: string[] = [];
  const declared = new Map<string, string>();
  const conflicts: string[] = [];
  const declare = (id: string, cls: string, doc: string) => {
    const prev = declared.get(id);
    if (prev && prev !== cls) conflicts.push(id);
    if (prev) return;
    declared.set(id, cls);
    globals.push(`---${oneLine(doc)}`, `---@type ${cls}`, `${id} = nil`, "");
  };

  const arrowClasses = new Map<string, string[]>();
  const cluTables: string[] = [];

  for (const clu of clus) {
    const ci = cluInterface(registry, clu);
    const cluClass = ci ? `CLU_${clu.hwType.toString(16)}_${clu.fwVersion.toString(16)}` : "GrentonObject";
    if (ci && !classes.has(cluClass)) classes.set(cluClass, classBlock(cluClass, ci, `CLU interface hw 0x${clu.hwType.toString(16)} fw 0x${clu.fwVersion.toString(16)}`));
    declare(clu.id, cluClass, `CLU ${clu.name} (${clu.ip})`);
    for (const r of clu.remotes) declare(r.id, "RemoteCLU", `remote CLU ${r.id} (${r.ip}), seen from ${clu.name}`);
    // OM notation: global named after the CLU, friendly names as fields
    const table = `${ident(clu.name)}__objects`;
    const fields: string[] = [];
    for (const m of clu.modules) {
      for (const io of m.ios) {
        const o = ioObject(registry, m, io.objectClass);
        const cls = o ? ident(o.name) : "GrentonObject";
        if (o && !classes.has(cls)) classes.set(cls, classBlock(cls, o.interface, `${o.name} (class ${o.class})`));
        declare(io.id, cls, `${io.name ?? io.id} on ${clu.name}, module ${m.serial}, channel ${io.channel}${io.inactive ? " (inactive)" : ""}`);
        const acls = o ? `${ident(o.name)}__om` : "GrentonObject";
        if (o && !arrowClasses.has(acls)) arrowClasses.set(acls, arrowClass(acls, undefined, o.interface, `${o.name}`));
        if (io.name && /^[A-Za-z_]\w*$/.test(io.name)) fields.push(`---@field ${io.name} ${acls} # ${io.id}, module ${m.serial}, channel ${io.channel}`);
      }
    }
    for (const v of clu.objects ?? []) {
      if (v.removed) continue;
      const o = objectInterface(registry, v.objectClass, v.version);
      const cls = o ? ident(o.name) : "GrentonObject";
      if (o && !classes.has(cls)) classes.set(cls, classBlock(cls, o.iface, `${o.name} (virtual object, class ${v.objectClass})`));
      declare(v.id, cls, `${v.name} on ${clu.name} (virtual ${o?.name ?? `class ${v.objectClass}`})`);
      const acls = o ? `${ident(o.name)}__om` : "GrentonObject";
      if (o && !arrowClasses.has(acls)) arrowClasses.set(acls, arrowClass(acls, undefined, o.iface, o.name));
      if (/^[A-Za-z_]\w*$/.test(v.name)) fields.push(`---@field ${v.name} ${acls} # ${v.id} (virtual)`);
    }
    // scripts of the CLU: CLU->script(args); every parameter optional (nil → its default)
    for (const s of clu.scripts) {
      if (!/^[A-Za-z_]\w*$/.test(s.name)) continue;
      const params = s.params.map((p) => `${ident(p.name)}?: ${p.type}`).join(", ");
      const doc = s.params.length ? s.params.map((p) => `${p.name} = ${JSON.stringify(p.default)}`).join(", ") : "no parameters";
      fields.push(`---@field ${s.name} fun(${params}) # script on ${clu.name} (defaults: ${doc})`);
    }
    cluTables.push(...arrowClass(table, undefined, ci, `CLU ${clu.name} (${clu.id}): objects by friendly name`).slice(0, -2), ...fields, `local ${table} = {}`, "");
    if (/^[A-Za-z_]\w*$/.test(clu.name) && clu.name !== clu.id) globals.push(`---CLU ${clu.name} (${clu.id}) in OM notation: ${clu.name}->OBJECT->Member`, `---@type ${table}`, `${clu.name} = nil`, "");
    else if (clu.name === clu.id) {
      // name == id (e.g. a CLU named after its id): the global serves both notations
      const k = globals.indexOf(`${clu.id} = nil`);
      if (k > 0) globals[k - 1] = `---@type ${cluClass} | ${table}`;
    }
  }
  const text = [PRELUDE, ...[...classes.values()].flat(), ...[...arrowClasses.values()].flat(), ...cluTables, "-- project objects", "", ...globals].join("\n");
  return { text, conflicts };
}
